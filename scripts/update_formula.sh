#!/usr/bin/env bash
# =============================================================================
#  SedirOS - regenerate the Homebrew formula (Formula/sediros.rb) for a release
#
#  Usage : ./scripts/update_formula.sh v1.0
#  Env   : SEDIROS_REPO           owner/name   (default: sediros/sediros)
#          SEDIROS_RELEASE_URL    base URL of the release files
#                                (default: GitHub releases download URL)
#
#  Run after the release has been published: it downloads the release's
#  SHA256SUMS and writes the CLI tarball checksums into the formula, so they
#  are never copied by hand. Commit the result.
#
#  Users install with:
#    brew tap sediros/sediros https://github.com/sediros/sediros
#    brew trust sediros/sediros
#    brew install sediros
# =============================================================================
set -Eeuo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TAG="${1:?usage: $0 v<release>}"
[[ "$TAG" =~ ^v[0-9]+\.[0-9]+(-rc[0-9]+)?$ ]] || { echo "tag must look like v1.0 or v1.0-rc1" >&2; exit 1; }
REPO="${SEDIROS_REPO:-sediros/sediros}"
BASE="${SEDIROS_RELEASE_URL:-https://github.com/${REPO}/releases/download/${TAG}}"
# SourceForge copies every GitHub release (webhook). brew downloads from it
# first (GitHub's release downloads can hang for hours) and falls back to
# GitHub; the checksums are the same files'.
MIRROR="${SEDIROS_MIRROR_URL:-https://downloads.sourceforge.net/project/sediros/${TAG}}"

# The GitHub API (gh) is a second path when the download URL fails.
sums="$(curl -fsSL "$BASE/SHA256SUMS" 2>/dev/null)" \
    || { [[ -z "${SEDIROS_RELEASE_URL:-}" ]] && command -v gh >/dev/null \
         && sums="$(gh release download "$TAG" -R "$REPO" -p SHA256SUMS -O -)"; } \
    || { echo "cannot download $BASE/SHA256SUMS" >&2; exit 1; }

# CLI version from the tarball names, e.g. sediros-0.3.0-aarch64-apple-darwin.tar.gz
version="$(sed -n 's/.*sediros-\([0-9][0-9.]*\)-aarch64-apple-darwin\.tar\.gz$/\1/p' <<<"$sums" | head -n1)"
[[ -n "$version" ]] || { echo "no CLI tarballs in SHA256SUMS" >&2; exit 1; }

sum_of() {
    local file="sediros-${version}-$1.tar.gz" s
    s="$(awk -v f="$file" '$2 == f || $2 == "*" f {print $1}' <<<"$sums")"
    [[ "$s" =~ ^[0-9a-f]{64}$ ]] || { echo "no checksum for $file" >&2; exit 1; }
    printf '%s' "$s"
}
mac_arm="$(sum_of aarch64-apple-darwin)"
mac_x86="$(sum_of x86_64-apple-darwin)"
linux_arm="$(sum_of aarch64-unknown-linux-musl)"
linux_x86="$(sum_of x86_64-unknown-linux-musl)"

# The mirror copies a new release some minutes after it is published: the
# formula must not point at files SourceForge does not have yet.
for t in aarch64-apple-darwin x86_64-apple-darwin aarch64-unknown-linux-musl x86_64-unknown-linux-musl; do
    f="sediros-${version}-${t}.tar.gz"
    curl -fsSL -o /dev/null -r 0-0 -A "Homebrew" "$MIRROR/$f" \
        || { echo "$f is not on the mirror yet ($MIRROR); try again later" >&2; exit 1; }
done

mkdir -p "$PROJECT_ROOT/Formula"
cat > "$PROJECT_ROOT/Formula/sediros.rb" <<EOF
# Generated by scripts/update_formula.sh for ${TAG}; do not edit by hand.
class Sediros < Formula
  desc "Fast, isolated QEMU VMs running SedirOS, a hardened Debian-based Linux"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "Apache-2.0"

  depends_on "qemu"

  on_macos do
    on_arm do
      url "${MIRROR}/sediros-${version}-aarch64-apple-darwin.tar.gz"
      mirror "${BASE}/sediros-${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${MIRROR}/sediros-${version}-x86_64-apple-darwin.tar.gz"
      mirror "${BASE}/sediros-${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${mac_x86}"
    end
  end

  on_linux do
    on_arm do
      url "${MIRROR}/sediros-${version}-aarch64-unknown-linux-musl.tar.gz"
      mirror "${BASE}/sediros-${version}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${MIRROR}/sediros-${version}-x86_64-unknown-linux-musl.tar.gz"
      mirror "${BASE}/sediros-${version}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${linux_x86}"
    end
  end

  def install
    bin.install "sediros"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sediros --version")
  end
end
EOF
echo "Formula/sediros.rb updated for ${TAG} (CLI ${version})"
